export function icon(name, size = 18) {
  const body = ICONS[name] || '';
  return raw(`<svg class="icon" width="${Number(size)}" height="${Number(size)}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`);
}

// fresh sostituisce il contenitore con una copia vuota, così i listener
// registrati da una vista precedente non si accumulano.
export function fresh(el) {
  const next = el.cloneNode(false);
  el.replaceWith(next);
  return next;
}
