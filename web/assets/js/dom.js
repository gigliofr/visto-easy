// Template HTML con escape automatico.
// Ogni valore interpolato viene sottoposto a escape, salvo che sia un
// frammento prodotto da html`` o marcato esplicitamente con raw().

class SafeHTML {
  constructor(value) {
    this.value = String(value);
  }

  toString() {
    return this.value;
  }
}

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;', '`': '&#96;' };

export function esc(value) {
  if (value === null || value === undefined) return '';
  return String(value).replace(/[&<>"'`]/g, (ch) => ESCAPES[ch]);
}

function renderValue(value) {
  if (value instanceof SafeHTML) return value.value;
  if (Array.isArray(value)) return value.map(renderValue).join('');
  if (value === null || value === undefined || value === false) return '';
  return esc(value);
}

export function html(strings, ...values) {
  let out = strings[0];
  for (let i = 0; i < values.length; i += 1) {
    out += renderValue(values[i]) + strings[i + 1];
  }
  return new SafeHTML(out);
}

// Solo per markup statico scritto nel codice (es. icone SVG). Mai per dati.
export function raw(markup) {
  return new SafeHTML(markup);
}

export function render(target, fragment) {
  const el = typeof target === 'string' ? document.querySelector(target) : target;
  if (!el) return null;
  el.innerHTML = renderValue(fragment);
  applyDynamicStyles(el);
  return el;
}

// La CSP vieta gli attributi style: le larghezze delle barre di avanzamento
// passano da data-pct e vengono applicate via CSSOM, che la CSP consente.
export function applyDynamicStyles(root = document) {
  root.querySelectorAll('[data-pct]').forEach((el) => {
    const pct = Math.max(0, Math.min(100, Number(el.dataset.pct) || 0));
    el.style.width = `${pct}%`;
  });
}

export function $(selector, root = document) {
  return root.querySelector(selector);
}

export function $$(selector, root = document) {
  return Array.from(root.querySelectorAll(selector));
}

export function on(root, event, selector, handler) {
  root.addEventListener(event, (ev) => {
    const target = ev.target.closest(selector);
    if (target && root.contains(target)) handler(ev, target);
  });
}

export function formValues(form) {
  const out = {};
  new FormData(form).forEach((value, key) => {
    out[key] = typeof value === 'string' ? value : value;
  });
  return out;
}

export function debounce(fn, ms) {
  let timer = null;
  const wrapped = (...args) => {
    clearTimeout(timer);
    timer = setTimeout(() => fn(...args), ms);
  };
  wrapped.flush = (...args) => {
    clearTimeout(timer);
    return fn(...args);
  };
  wrapped.cancel = () => clearTimeout(timer);
  return wrapped;
}

